// scripts/coord/build-handoff-lib.mjs
// Pure core for rendering the "recent sessions" index in handoff.md from the
// per-session entry files under handoff/sessions/ (plan 249, Task 3).
//
// Plan 205 already removed the real contention: each session writes its OWN
// handoff/sessions/<date>-session-N.md (no append-conflict on a shared file).
// What was missing is a single place to SEE them all. This renders a thin,
// newest-first index — one link line per session — into a sentinel region just
// below handoff.md's pointer header, leaving the frozen pre-split history below
// untouched.
//
// Deliberately a THIN INDEX (links + one-line status), not a full concatenation:
// it stays small, and it is an ON-DEMAND view — NOT written on the per-session
// hot path — so it never re-introduces the handoff.md write-contention plan 205
// eliminated. `/state` still reads handoff/sessions/ directly; this is a human
// convenience aggregate.

export const HANDOFF_RECENT_START =
  '<!-- HANDOFF:RECENT-START (generated by scripts/build-handoff.mjs from handoff/sessions/ — do not hand-edit between the sentinels) -->';
export const HANDOFF_RECENT_END = '<!-- HANDOFF:RECENT-END -->';

// plan 2891 T4: the `YYYY-MM-DD` session-entry date SHAPE, spelled ONCE. It was written
// three times — claim-plan-lib's SESSION_ENTRY_DATE_RX (which validates the `--date` a
// filename is built from), done-worktree-lib's SESSION_ENTRY_BASENAME_RX anchor (which
// decides whether a basename IS a session entry) and this module's parseSessionFilename
// (which ORDERS them) — and the first two are two halves of ONE invariant that was held in
// sync only by a comment cross-referencing the other file. A source fragment rather than a
// finished RegExp because each consumer anchors it differently (whole-string, basename
// prefix, capturing group); the SHAPE is the invariant, not the anchoring.
//
// This module is the home because it is the DEPENDENCY-FREE one of the three (it imports
// nothing, so both importers can take it without a cycle or an IO-at-import surprise) and it
// already owns the fullest form of the shape in parseSessionFilename below.
//
// Shape-only, not a calendar check — see assertSessionEntryDate's own note: a shape-valid but
// impossible date (2026-13-40) still sorts and sequences exactly like a real one.
export const SESSION_ENTRY_DATE_SHAPE = String.raw`\d{4}-\d{2}-\d{2}`;

// Parse a session filename "YYYY-MM-DD-session-<N>[suffix].md" into a sortable
// record. <N> is numeric; an optional letter suffix (19b) disambiguates same-day
// parallel sessions. Returns null for anything that isn't a session entry
// (e.g. README.md).
const SESSION_FILENAME_RX = new RegExp(
  `^(${SESSION_ENTRY_DATE_SHAPE})-session-(\\d+)([a-z]*)\\.md$`,
);
export function parseSessionFilename(name) {
  const m = name.match(SESSION_FILENAME_RX);
  if (!m) return null;
  return { name, date: m[1], num: Number(m[2]), suffix: m[3] || '' };
}

// Newest-first: highest session number first, suffix descending as tiebreaker,
// date as final tiebreaker. Numeric (not lexical) so 100 sorts above 99.
export function sortSessionsNewestFirst(names) {
  return names
    .map(parseSessionFilename)
    .filter(Boolean)
    .sort(
      (a, b) => b.num - a.num || b.suffix.localeCompare(a.suffix) || b.date.localeCompare(a.date),
    )
    .map((r) => r.name);
}

// First `## ` heading of an entry (its title line), trimmed of the leading `## `.
export function entryHeading(content) {
  const m = content.match(/^##\s+(.+?)\s*$/m);
  return m ? m[1].trim() : '';
}

// First **Status:** line's value (one line), markdown stripped to plain text.
export function entryStatus(content) {
  const m = content.match(/^\*\*Status:\*\*\s*(.+?)\s*$/m);
  if (!m) return '';
  return m[1].replace(/\*\*/g, '').trim();
}

// Render one index line: `- [<heading>](<sessionsLinkPrefix>/<name>) — <status>`.
// sessionsLinkPrefix is the sessions dir RELATIVE to the rolling-handoff file's dir
// (plan 857): legacy root layout → 'handoff/sessions'; one-tree layout (current.md +
// sessions/ both under docs/handoff/) → 'sessions'. Default keeps legacy callers/tests.
export function renderIndexLine(
  { name, heading, status },
  sessionsLinkPrefix = 'handoff/sessions',
) {
  const label = heading || name.replace(/\.md$/, '');
  const tail = status ? ` — ${status}` : '';
  return `- [${label}](${sessionsLinkPrefix}/${name})${tail}`;
}

// Build the sentinel-fenced recent block from entry records
// ({ name, heading, status }), already newest-first.
export function renderRecentBlock(entries, sessionsLinkPrefix = 'handoff/sessions') {
  const out = [HANDOFF_RECENT_START, '', '## Recent sessions (generated — newest first)', ''];
  if (entries.length === 0) out.push('_(no per-session entries yet)_');
  for (const e of entries) out.push(renderIndexLine(e, sessionsLinkPrefix));
  out.push('', HANDOFF_RECENT_END);
  return out.join('\n');
}

// Splice the block between the sentinels if present; otherwise insert it right
// after the first standalone `---` separator (the pointer-header divider),
// before the frozen history.
export function spliceRecentBlock(handoffContent, block) {
  const lines = handoffContent.split('\n');
  const startIdx = lines.findIndex((l) => l.includes(HANDOFF_RECENT_START));
  const endIdx = lines.findIndex((l) => l.includes(HANDOFF_RECENT_END));
  if (startIdx !== -1 && endIdx !== -1 && endIdx >= startIdx) {
    return [...lines.slice(0, startIdx), block, ...lines.slice(endIdx + 1)].join('\n');
  }
  const sep = lines.findIndex((l) => l.trim() === '---');
  const at = sep === -1 ? lines.length : sep + 1;
  return [...lines.slice(0, at), '', block, ...lines.slice(at)].join('\n');
}
